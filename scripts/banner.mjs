// Emits assets/banner.svg (dark) and assets/banner-light.svg (light) from one
// template, so the two never drift. Bento identity of the portfolio: rounded
// tiles, Big Shoulders Display for titles, Instrument Sans for text.
// GitHub never loads a font inside an SVG image, so each stack falls back to a
// system face (Impact for the titles). Run: node scripts/banner.mjs
import { writeFileSync } from 'node:fs';

const C = { champ: '#0A1628', champ2: '#10213B', craie: '#E9E6DE', encre2: '#6EC3FF', signal: '#FF4F6E' };
const D = "'Big Shoulders Display', Impact, 'Arial Narrow', sans-serif";
const T = "'Instrument Sans', Arial, Helvetica, sans-serif";
const W = 1060, H = 280, G = 8, R = 10;

const tile = (x, y, w, h, fill) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${R}" fill="${fill}"/>`;
const cw = (336 - 2 * G) / 3;

function banner(t) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="Sitraka Rasatarivony, full-stack TypeScript developer, Antananarivo. Three years of experience, internship included.">
  <!-- Generated by scripts/banner.mjs: do not edit by hand. -->
  <rect width="${W}" height="${H}" rx="${R + G}" fill="${t.page}"/>

  ${tile(G, G, 700 - G, H - 2 * G, t.main)}
  <text x="40" y="58" font-family="${T}" font-size="13" font-weight="700" letter-spacing="2" fill="${t.line1}" opacity="0.72">SITRAKA RASATARIVONY · ANTANANARIVO, MADAGASCAR</text>
  <text x="38" y="152" font-family="${D}" font-size="92" font-weight="900" fill="${t.line1}">FULL-STACK</text>
  <text x="38" y="236" font-family="${D}" font-size="92" font-weight="900" fill="${t.line2}">TYPESCRIPT</text>
  ${t.bars.map((c, i) => `<rect x="${560 + i * 40}" y="${H - G - 36}" width="34" height="6" fill="${c}"/>`).join('')}

  ${tile(708, G, 336, 148, t.years)}
  <text x="732" y="96" font-family="${D}" font-size="76" font-weight="900" fill="${C.champ}">3 YEARS</text>
  <text x="734" y="122" font-family="${T}" font-size="13" font-weight="700" letter-spacing="1.5" fill="${C.champ}">OF EXPERIENCE</text>
  <text x="734" y="140" font-family="${T}" font-size="13" font-weight="700" letter-spacing="1.5" fill="${C.champ}">INTERNSHIP INCLUDED</text>

  ${t.chips.map(([label, bg, ink], i) => {
    const x = 708 + i * (cw + G);
    return `${tile(x, 164, cw, H - G - 164, bg)}<text x="${x + cw / 2}" y="${164 + (H - G - 164) / 2 + 7}" text-anchor="middle" font-family="${T}" font-size="15" font-weight="700" fill="${ink}">${label}</text>`;
  }).join('\n  ')}
</svg>
`;
}

// Light: craie paper, white main tile; the light blue cannot carry text on white,
// so the second line takes the coral and the blue moves to a tile behind ink.
const dark = {
  page: C.champ, main: C.champ2, line1: C.craie, line2: C.encre2, years: C.signal,
  bars: [C.encre2, C.signal, C.craie],
  chips: [['NestJS', C.encre2, C.champ], ['React', C.craie, C.champ], ['PostgreSQL', C.champ2, C.craie]]
};
const light = {
  page: C.craie, main: '#FFFFFF', line1: C.champ, line2: C.signal, years: C.encre2,
  bars: [C.encre2, C.signal, C.champ],
  chips: [['NestJS', C.champ, C.craie], ['React', C.signal, C.champ], ['PostgreSQL', '#FFFFFF', C.champ]]
};

writeFileSync(new URL('../assets/banner.svg', import.meta.url), banner(dark));
writeFileSync(new URL('../assets/banner-light.svg', import.meta.url), banner(light));
